def test_two_resets_produce_the_same_canonical_state(
    database: Settings, bundle: FixtureBundle
) -> None:
    factory = SessionFactory(database.database_url)
    try:
        with transaction(factory) as session:
            first = reset_demo(session, bundle, confirmation="--confirm-fictional-demo")
        first_digest = canonical_state(database)
        first_counts = seeded_row_counts_from(database)

        with transaction(factory) as session:
            second = reset_demo(session, bundle, confirmation="--confirm-fictional-demo")
        second_digest = canonical_state(database)
        second_counts = seeded_row_counts_from(database)
    finally:
        factory.dispose()

    assert first.counts == second.counts
    assert first_counts == second_counts
    assert first_digest == second_digest


