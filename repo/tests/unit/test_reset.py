def test_refused_reset_leaves_the_database_unchanged(
    database: Settings, bundle: FixtureBundle
) -> None:
    factory = SessionFactory(database.database_url)
    try:
        with transaction(factory) as session:
            reset_demo(session, bundle, confirmation="--confirm-fictional-demo")
        before = canonical_state(database)
        with pytest.raises(ValidationError):
            with transaction(factory) as session:
                reset_demo(session, bundle, confirmation="please reset")
        after = canonical_state(database)
    finally:
        factory.dispose()
    assert before == after


def test_seeded_state_contains_the_controlled_scenarios(
    database: Settings, bundle: FixtureBundle
) -> None:
    factory = SessionFactory(database.database_url)
    try:
        with transaction(factory) as session:
            reset_demo(session, bundle, confirmation="--confirm-fictional-demo")
        with factory() as session:
            applications = session.execute(select(func.count()).select_from(Base.metadata.tables["applications"])).scalar_one()
            snapshots = session.execute(select(func.count()).select_from(Base.metadata.tables["source_snapshots"])).scalar_one()
            payments = session.execute(select(func.count()).select_from(Base.metadata.tables["payments"])).scalar_one()
            allocations = session.execute(select(func.count()).select_from(Base.metadata.tables["allocations"])).scalar_one()
    finally:
        factory.dispose()

    assert applications == 13
    assert snapshots == 41
    assert payments == 8
    assert allocations == 1


